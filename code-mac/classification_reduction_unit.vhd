-- Input classification + range reduction (5 pipeline stages)
--   stage 1 : unpack, classify
--   stage 2 : read the window W of 2/pi, indexed by the exponent
--   stage 3a: two partial products M x W_hi and M x W_lo
--   stage 3b: add the partial products -> P = x * 2/pi (mod 4)
--   stage 4 : round to nearest k, |r|, sign of r, small-argument flag

ENTITY classification_reduction_unit IS
    PORT (
        clk : IN STD_LOGIC;
        rst : IN STD_LOGIC;
        en : IN STD_LOGIC;
        x_in : IN STD_LOGIC_VECTOR(31 DOWNTO 0);
        valid_in : IN STD_LOGIC;
        -- 7 = sign_r;
        -- 6 = sign_x;
        -- 5:4 = kmod4;
        -- 3:1 = input_cls
        -- 0: small input flag
        side_info_out : OUT STD_LOGIC_VECTOR(7 DOWNTO 0);
        x_out : OUT STD_LOGIC_VECTOR(31 DOWNTO 0);
        z_out : OUT STD_LOGIC_VECTOR(45 DOWNTO 0);      -- |r|, 2 int + 44 frac bits
        rsmall_out : OUT STD_LOGIC_VECTOR(47 DOWNTO 0); -- |r| bits 2^-13 .. 2^-60
        valid_out : OUT STD_LOGIC
    );
END classification_reduction_unit;

