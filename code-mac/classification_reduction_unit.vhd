                stage3a_pp_lo <= stage2_M * stage2_W(40 DOWNTO 0);

                stage3a_valid <= stage2_valid;
                stage3a_class <= stage2_class;
                stage3a_sign_x <= stage2_sign_x;
                stage3a_x <= stage2_x;
            END IF;
        END IF;
    END PROCESS;

    -- stage 3b: P = pp_hi * 2^41 + pp_lo, only the low 82 bits are kept
    stage3b : PROCESS (clk)
    BEGIN
        IF rising_edge(clk) THEN
            IF rst = '1' THEN
                stage3b_valid <= '0';
            ELSIF en = '1' THEN
                stage3b_prod <= (stage3a_pp_hi(40 DOWNTO 0) & (40 DOWNTO 0 => '0'))
