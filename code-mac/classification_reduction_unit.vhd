    -- stage 1: unpack and classify
    stage1 : PROCESS (clk)
    BEGIN
        IF rising_edge(clk) THEN
            IF rst = '1' THEN
                stage1_valid <= '0';
            ELSIF en = '1' THEN
                IF x_exp = "11111111" THEN
                    IF x_frac = 0 THEN
